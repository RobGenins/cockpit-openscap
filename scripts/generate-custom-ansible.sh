#!/bin/bash
# generate-custom-ansible.sh - Generate custom Ansible playbook
# Part of OpenSCAP Cockpit Plugin v4.4.3
# Uses pre-extracted fixes for instant generation

SCAN_ID="$1"
RULE_IDS_JSON="$2"
SCAN_DIR="/usr/share/cockpit/cockpit-openscap/scans/${SCAN_ID}"
FIXES_DIR="${SCAN_DIR}/fixes/ansible"
SCAN_INFO="${SCAN_DIR}/scan-info.json"
TIMESTAMP=$(date +%Y%m%d-%H%M%S)
OUTPUT_FILE="${SCAN_DIR}/custom-playbook-${TIMESTAMP}.yml"

# Validate inputs
if [ -z "${SCAN_ID}" ]; then
    echo "Error: Scan ID required" >&2
    exit 1
fi

if [ -z "${RULE_IDS_JSON}" ]; then
    echo "Error: Rule IDs JSON required" >&2
    exit 1
fi

# Check if fixes have been extracted
if [ ! -d "${FIXES_DIR}" ]; then
    # Try to extract them now
    bash "/usr/share/cockpit/cockpit-openscap/scripts/extract-fixes.sh" "${SCAN_ID}" >&2
fi

if [ ! -d "${FIXES_DIR}" ]; then
    echo "Error: No extracted fixes found for this scan" >&2
    exit 1
fi

# Parse rule IDs from JSON
RULE_IDS=$(echo "${RULE_IDS_JSON}" | grep -o '"[^"]*xccdf[^"]*"' | tr -d '"')

if [ -z "${RULE_IDS}" ]; then
    echo "Error: No valid rule IDs found in input" >&2
    exit 1
fi

RULE_COUNT=$(echo "${RULE_IDS}" | wc -l)

# Get profile name
PROFILE_NAME="Unknown"
if [ -f "${SCAN_INFO}" ]; then
    PROFILE_NAME=$(grep -o '"profile"[[:space:]]*:[[:space:]]*"[^"]*"' "${SCAN_INFO}" 2>/dev/null | sed 's/.*"profile"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/' || echo "Unknown")
fi

# Write header
cat > "${OUTPUT_FILE}" << HEADER
---
###############################################################################
# Custom OpenSCAP Remediation Playbook
# Generated by OpenSCAP Cockpit Plugin
#
# Generation Date: $(date '+%Y-%m-%d %H:%M:%S')
# Source Scan ID:  ${SCAN_ID}
# Profile:         ${PROFILE_NAME}
# Selected Fixes:  ${RULE_COUNT}
#
###############################################################################
# WARNING: Review this playbook before execution!
# This playbook will modify system configuration.
# Ensure you have backups and understand each change.
#
# NOTE: Each task has ignore_errors: yes so all fixes are attempted.
# Some tasks may fail due to missing packages, services, or configuration.
# Review the playbook output to see which fixes succeeded/failed.
###############################################################################

- name: OpenSCAP Custom Remediation
  hosts: all
  become: true
  ignore_unreachable: true
  vars:
    remediation_date: "$(date '+%Y-%m-%d %H:%M:%S')"
    scan_id: "${SCAN_ID}"
    profile: "${PROFILE_NAME}"
    fixes_attempted: 0
    fixes_failed: 0

  tasks:
    - name: Display remediation information
      debug:
        msg: |
          OpenSCAP Custom Remediation Playbook
          Generated: {{ remediation_date }}
          Scan ID: {{ scan_id }}
          Profile: {{ profile }}
          Fixes to apply: ${RULE_COUNT}

HEADER

# Append each selected fix
INCLUDED=0
while IFS= read -r RULE_ID; do
    [ -z "${RULE_ID}" ] && continue

    FIX_FILE="${FIXES_DIR}/${RULE_ID}.yml"
    if [ -f "${FIX_FILE}" ]; then
        ((INCLUDED++))
        # Add comment for this fix
        echo "    # Fix ${INCLUDED}: ${RULE_ID}" >> "${OUTPUT_FILE}"
        # Add the task (already has proper YAML formatting)
        cat "${FIX_FILE}" >> "${OUTPUT_FILE}"
        # Add ignore_errors to ensure playbook continues
        echo "      ignore_errors: yes" >> "${OUTPUT_FILE}"
        echo "" >> "${OUTPUT_FILE}"
    fi
done <<< "${RULE_IDS}"

# Write footer
cat >> "${OUTPUT_FILE}" << 'FOOTER'

    - name: Remediation complete
      debug:
        msg: |
          Remediation playbook completed successfully.
          Please review any changes made and consider
          rebooting if kernel or system services were modified.
FOOTER

# Set permissions
chmod 644 "${OUTPUT_FILE}"

# Output the file path
echo "${OUTPUT_FILE}"
exit 0
