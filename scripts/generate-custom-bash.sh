#!/bin/bash
# generate-custom-bash.sh - Generate custom Bash remediation script
# Part of OpenSCAP Cockpit Plugin v4.4.3
# Uses pre-extracted fixes for instant generation

SCAN_ID="$1"
RULE_IDS_JSON="$2"
SCAN_DIR="/usr/share/cockpit/cockpit-openscap/scans/${SCAN_ID}"
FIXES_DIR="${SCAN_DIR}/fixes/bash"
SCAN_INFO="${SCAN_DIR}/scan-info.json"
TIMESTAMP=$(date +%Y%m%d-%H%M%S)
OUTPUT_FILE="${SCAN_DIR}/custom-remediation-${TIMESTAMP}.sh"

# Validate inputs
if [ -z "${SCAN_ID}" ]; then
    echo "Error: Scan ID required" >&2
    exit 1
fi

if [ -z "${RULE_IDS_JSON}" ]; then
    echo "Error: Rule IDs JSON required" >&2
    exit 1
fi

# Check if fixes have been extracted
if [ ! -d "${FIXES_DIR}" ]; then
    # Try to extract them now
    bash "/usr/share/cockpit/cockpit-openscap/scripts/extract-fixes.sh" "${SCAN_ID}" >&2
fi

if [ ! -d "${FIXES_DIR}" ]; then
    echo "Error: No extracted fixes found for this scan" >&2
    exit 1
fi

# Parse rule IDs from JSON
RULE_IDS=$(echo "${RULE_IDS_JSON}" | grep -o '"[^"]*xccdf[^"]*"' | tr -d '"')

if [ -z "${RULE_IDS}" ]; then
    echo "Error: No valid rule IDs found in input" >&2
    exit 1
fi

RULE_COUNT=$(echo "${RULE_IDS}" | wc -l)

# Get profile name
PROFILE_NAME="Unknown"
if [ -f "${SCAN_INFO}" ]; then
    PROFILE_NAME=$(grep -o '"profile"[[:space:]]*:[[:space:]]*"[^"]*"' "${SCAN_INFO}" 2>/dev/null | sed 's/.*"profile"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/' || echo "Unknown")
fi

# Write header
cat > "${OUTPUT_FILE}" << HEADER
#!/bin/bash
###############################################################################
# Custom OpenSCAP Remediation Script
# Generated by OpenSCAP Cockpit Plugin
###############################################################################
#
# Generation Date: $(date '+%Y-%m-%d %H:%M:%S')
# Source Scan ID:  ${SCAN_ID}
# Profile:         ${PROFILE_NAME}
# Selected Fixes:  ${RULE_COUNT}
#
###############################################################################
# WARNING: Review this script before execution!
# This script will modify system configuration.
# Ensure you have backups and understand each change.
###############################################################################

# NOTE: We do NOT use 'set -e' so the script continues even if some fixes fail.
# Some fixes may fail due to missing packages, services, or system configuration.
# Review the output after completion to see which fixes succeeded/failed.

FIXES_ATTEMPTED=0
FIXES_FAILED=0

echo "=============================================="
echo "OpenSCAP Custom Remediation Script"
echo "Generated: $(date '+%Y-%m-%d %H:%M:%S')"
echo "Fixes to apply: ${RULE_COUNT}"
echo "=============================================="
echo ""

HEADER

# Append each selected fix
FIX_NUM=0
INCLUDED=0
while IFS= read -r RULE_ID; do
    [ -z "${RULE_ID}" ] && continue
    ((FIX_NUM++))

    FIX_FILE="${FIXES_DIR}/${RULE_ID}.sh"
    if [ -f "${FIX_FILE}" ]; then
        ((INCLUDED++))
        {
            echo ""
            echo "###############################################################################"
            echo "# Fix ${INCLUDED}: ${RULE_ID}"
            echo "###############################################################################"
            echo "((FIXES_ATTEMPTED++))"
            echo "echo \"[Fix ${INCLUDED}] Applying: ${RULE_ID}\""
            echo "if ( "
            cat "${FIX_FILE}"
            echo ""
            echo "); then"
            echo "    echo \"[Fix ${INCLUDED}] SUCCESS\""
            echo "else"
            echo "    echo \"[Fix ${INCLUDED}] FAILED (continuing...)\""
            echo "    ((FIXES_FAILED++))"
            echo "fi"
            echo ""
        } >> "${OUTPUT_FILE}"
    fi
done <<< "${RULE_IDS}"

# Write footer
cat >> "${OUTPUT_FILE}" << 'FOOTER'

###############################################################################
# Remediation Complete
###############################################################################

echo ""
echo "=============================================="
echo "Remediation script completed"
echo "Timestamp: $(date '+%Y-%m-%d %H:%M:%S')"
echo "=============================================="
echo ""
echo "SUMMARY:"
echo "  Fixes attempted: ${FIXES_ATTEMPTED}"
echo "  Fixes failed:    ${FIXES_FAILED}"
echo "  Fixes succeeded: $((FIXES_ATTEMPTED - FIXES_FAILED))"
echo ""
if [ ${FIXES_FAILED} -gt 0 ]; then
    echo "WARNING: Some fixes failed. Review output above for details."
    echo ""
fi
echo "IMPORTANT: Please review any changes made and"
echo "consider rebooting if kernel or system services"
echo "were modified."
echo ""
echo "Run another scan to verify improvements."
echo ""
FOOTER

# Make executable
chmod 755 "${OUTPUT_FILE}"

# Output the file path
echo "${OUTPUT_FILE}"
exit 0
