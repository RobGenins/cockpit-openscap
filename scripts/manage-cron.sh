#!/bin/bash
# manage-cron.sh - Manage scheduled OpenSCAP scans via cron
# Part of OpenSCAP Cockpit Plugin v4.6.0
# Usage: manage-cron.sh [get|set|remove] [cron_expression] [datastream] [profile_id]

ACTION="${1:-get}"
CRON_EXPR="${2}"
DATASTREAM="${3}"
PROFILE_ID="${4}"

CRON_MARKER="# cockpit-openscap-scheduled-scan"
SCAN_SCRIPT="/usr/share/cockpit/cockpit-openscap/scripts/scheduled-scan.sh"
LOG_FILE="/var/log/cockpit-openscap/master.log"
CONFIG_FILE="/usr/share/cockpit/cockpit-openscap/cron-config.json"

log() {
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] CRON: $1" >> "${LOG_FILE}" 2>/dev/null
}

# Get current cron job
get_cron() {
    local cron_line
    cron_line=$(crontab -l 2>/dev/null | grep "${CRON_MARKER}")

    if [ -n "${cron_line}" ]; then
        # Extract schedule and read config for profile info
        if [ -f "${CONFIG_FILE}" ]; then
            cat "${CONFIG_FILE}"
        else
            # Parse from cron line
            local schedule
            schedule=$(echo "${cron_line}" | sed "s| ${SCAN_SCRIPT}.*||")
            echo "{\"enabled\": true, \"schedule\": \"${schedule}\", \"profile\": \"Unknown\", \"datastream\": \"Unknown\"}"
        fi
    else
        echo '{"enabled": false}'
    fi
}

# Set cron job
set_cron() {
    if [ -z "${CRON_EXPR}" ] || [ -z "${DATASTREAM}" ] || [ -z "${PROFILE_ID}" ]; then
        echo '{"status": "error", "message": "Missing required parameters"}'
        exit 1
    fi

    log "Setting cron schedule: ${CRON_EXPR} for profile ${PROFILE_ID}"

    # Create scheduled scan script if it doesn't exist
    create_scan_script

    # Remove any existing cron job first
    crontab -l 2>/dev/null | grep -v "${CRON_MARKER}" | crontab - 2>/dev/null

    # Add new cron job
    (crontab -l 2>/dev/null; echo "${CRON_EXPR} ${SCAN_SCRIPT} '${DATASTREAM}' '${PROFILE_ID}' ${CRON_MARKER}") | crontab -

    # Save config for display
    cat > "${CONFIG_FILE}" << EOF
{
    "enabled": true,
    "schedule": "${CRON_EXPR}",
    "profile": "${PROFILE_ID}",
    "datastream": "${DATASTREAM}",
    "created": "$(date -Iseconds)"
}
EOF

    log "Cron job created successfully"
    echo '{"status": "success", "message": "Schedule saved"}'
}

# Remove cron job
remove_cron() {
    log "Removing cron schedule"

    # Remove from crontab
    crontab -l 2>/dev/null | grep -v "${CRON_MARKER}" | crontab - 2>/dev/null

    # Remove config file
    rm -f "${CONFIG_FILE}"

    log "Cron job removed"
    echo '{"status": "success", "message": "Schedule removed"}'
}

# Create the scheduled scan script
create_scan_script() {
    cat > "${SCAN_SCRIPT}" << 'SCRIPT'
#!/bin/bash
# scheduled-scan.sh - Run OpenSCAP scan from cron
# Auto-generated by cockpit-openscap

DATASTREAM="$1"
PROFILE_ID="$2"

INSTALL_DIR="/usr/share/cockpit/cockpit-openscap"
LOG_FILE="/var/log/cockpit-openscap/master.log"
SCAN_ID="$(date +%Y-%m-%dT%H-%M-%S)-scheduled"

log() {
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] SCHEDULED: $1" >> "${LOG_FILE}"
}

log "Starting scheduled scan with profile ${PROFILE_ID}"

# Run the scan
"${INSTALL_DIR}/scripts/run-scan.sh" "${DATASTREAM}" "${PROFILE_ID}" "${SCAN_ID}" >> "${LOG_FILE}" 2>&1

if [ $? -eq 0 ]; then
    log "Scheduled scan completed successfully"
else
    log "ERROR: Scheduled scan failed"
fi
SCRIPT

    chmod 755 "${SCAN_SCRIPT}"
}

# Main
case "${ACTION}" in
    get)
        get_cron
        ;;
    set)
        set_cron
        ;;
    remove)
        remove_cron
        ;;
    *)
        echo '{"status": "error", "message": "Unknown action"}'
        exit 1
        ;;
esac
